#!/usr/bin/env bash
# Local development database for clubfindr: Postgres + schema + synthetic seed,
# and a matching clubfindr/.env.
#
#   dev/setup.sh            set up (or refresh) everything
#   dev/setup.sh --force    also overwrite a .env that this script did not write
#   dev/setup.sh --stop     stop the Postgres this script started
#
# Safe to re-run: it reuses a running server, creates the database and schema
# only when missing, and reloads the seed (which wipes the clubfindr tables).
#
# Postgres, first match wins:
#   1. A server already accepting the dev credentials below.
#   2. DEV_PG_ADMIN_URL set: a superuser URL for an existing server; the dev
#      role and database are created there.
#   3. Local Postgres binaries (initdb/pg_ctl): a private cluster in
#      dev/.pgdata, owned by this checkout.
#   4. Docker: a postgres:16 container named clubfindr-dev-postgres.
#
# Settings (environment variables, all optional):
#   DEV_PG_HOST (127.0.0.1)  DEV_PG_USER (clubfindr_dev)
#   DEV_PG_PASSWORD (clubfindr_dev)  DEV_PG_ADMIN_URL  DEV_PG_IMAGE (postgres:16)
#
# Guard: seed.sql empties every clubfindr table, so this script only ever
# loads it into a database named clubfindr_dev on port 54329. DEV_PG_DB and
# DEV_PG_PORT exist only to be checked against those values.
set -euo pipefail

DEV_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
APP_DIR="$(dirname "$DEV_DIR")"

HOST="${DEV_PG_HOST:-127.0.0.1}"
PORT="${DEV_PG_PORT:-54329}"
DB="${DEV_PG_DB:-clubfindr_dev}"
DBUSER="${DEV_PG_USER:-clubfindr_dev}"
DBPASS="${DEV_PG_PASSWORD:-clubfindr_dev}"
IMAGE="${DEV_PG_IMAGE:-postgres:16}"
CONTAINER=clubfindr-dev-postgres
PGDATA_DIR="$DEV_DIR/.pgdata"
ENV_FILE="$APP_DIR/.env"
ENV_MARKER="# Generated by dev/setup.sh"

SEED_DB=clubfindr_dev
SEED_PORT=54329

FORCE=0
STOP=0
case "${1:-}" in
--force) FORCE=1 ;;
--stop) STOP=1 ;;
"") ;;
*)
	echo "usage: dev/setup.sh [--force|--stop]" >&2
	exit 2
	;;
esac

log() { echo "==> $*"; }
die() {
	echo "setup: $*" >&2
	exit 1
}

# Postgres server binaries are often not on PATH (Debian/Ubuntu keep them in
# /usr/lib/postgresql/<version>/bin)
find_bin() {
	local name=$1 candidate
	if command -v "$name" >/dev/null 2>&1; then
		command -v "$name"
		return 0
	fi
	for candidate in $(ls -d /usr/lib/postgresql/*/bin /usr/local/pgsql/bin /opt/homebrew/bin 2>/dev/null | sort -rV); do
		if [ -x "$candidate/$name" ]; then
			echo "$candidate/$name"
			return 0
		fi
	done
	return 1
}

# initdb and postgres refuse to run as root; use the postgres OS user then
as_db_owner() {
	if [ "$(id -u)" = 0 ]; then
		id postgres >/dev/null 2>&1 || die "running as root and there is no 'postgres' user to own the cluster"
		runuser -u postgres -- "$@"
	else
		"$@"
	fi
}

stop_server() {
	if [ -f "$PGDATA_DIR/PG_VERSION" ]; then
		local pg_ctl
		pg_ctl=$(find_bin pg_ctl) || die "pg_ctl not found"
		as_db_owner "$pg_ctl" -D "$PGDATA_DIR" stop -m fast || true
	fi
	if command -v docker >/dev/null 2>&1 && docker ps -q -f "name=^${CONTAINER}$" | grep -q .; then
		docker stop "$CONTAINER" >/dev/null && echo "stopped container $CONTAINER"
	fi
}

if [ $STOP = 1 ]; then
	stop_server
	exit 0
fi

if [ "$DB" != "$SEED_DB" ] || [ "$PORT" != "$SEED_PORT" ]; then
	die "refusing to run: the seed only loads into database '$SEED_DB' on port $SEED_PORT
(got DEV_PG_DB='$DB', DEV_PG_PORT='$PORT')"
fi

# psql on the host if there is one, else inside the container
USE_DOCKER_PSQL=0
psql_dev() { # psql_dev <database> [psql args...]
	local database=$1
	shift
	if [ $USE_DOCKER_PSQL = 1 ]; then
		docker exec -i -e PGPASSWORD="$DBPASS" "$CONTAINER" \
			psql -X -q -v ON_ERROR_STOP=1 -h 127.0.0.1 -p 5432 -U "$DBUSER" -d "$database" "$@"
	else
		PGPASSWORD="$DBPASS" PGCONNECT_TIMEOUT=3 psql -X -q -v ON_ERROR_STOP=1 \
			-h "$HOST" -p "$PORT" -U "$DBUSER" -d "$database" "$@"
	fi
}

dev_login_works() { psql_dev postgres -tAc 'select 1' >/dev/null 2>&1; }

wait_until_ready() {
	local _
	for _ in $(seq 1 60); do
		dev_login_works && return 0
		sleep 1
	done
	die "Postgres did not accept connections on $HOST:$PORT within 60s"
}

# --- 1. Postgres -------------------------------------------------------------

MODE=""

if command -v psql >/dev/null 2>&1 && dev_login_works; then
	MODE=existing
	log "Using the Postgres already running on $HOST:$PORT"
elif [ -n "${DEV_PG_ADMIN_URL:-}" ]; then
	command -v psql >/dev/null 2>&1 || die "DEV_PG_ADMIN_URL needs psql on PATH"
	MODE=admin
	log "Creating role $DBUSER on the server in DEV_PG_ADMIN_URL"
	psql -X -q -v ON_ERROR_STOP=1 "$DEV_PG_ADMIN_URL" -v u="$DBUSER" -v p="$DBPASS" <<'SQL'
SELECT format('CREATE ROLE %I LOGIN PASSWORD %L CREATEDB', :'u', :'p')
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = :'u') \gexec
SELECT format('ALTER ROLE %I LOGIN PASSWORD %L', :'u', :'p') \gexec
SQL
	wait_until_ready
elif INITDB=$(find_bin initdb) && PG_CTL=$(find_bin pg_ctl); then
	MODE=local
	command -v psql >/dev/null 2>&1 || die "psql not found on PATH"
	if [ ! -f "$PGDATA_DIR/PG_VERSION" ]; then
		log "Creating a private Postgres cluster in dev/.pgdata"
		mkdir -p "$PGDATA_DIR"
		chmod 700 "$PGDATA_DIR"
		[ "$(id -u)" = 0 ] && chown postgres "$PGDATA_DIR"
		pwfile=$(mktemp)
		printf '%s\n' "$DBPASS" >"$pwfile"
		chmod 644 "$pwfile"
		as_db_owner "$INITDB" -D "$PGDATA_DIR" -U "$DBUSER" --pwfile="$pwfile" \
			--auth=scram-sha-256 --encoding=UTF8 --no-locale >/dev/null
		rm -f "$pwfile"
	fi
	if ! as_db_owner "$PG_CTL" -D "$PGDATA_DIR" status >/dev/null 2>&1; then
		log "Starting the private cluster on $HOST:$PORT"
		as_db_owner "$PG_CTL" -D "$PGDATA_DIR" -w -l "$PGDATA_DIR/server.log" \
			-o "-p $PORT -c listen_addresses=$HOST -k $PGDATA_DIR" start >/dev/null
	fi
	wait_until_ready
elif command -v docker >/dev/null 2>&1; then
	MODE=docker
	command -v psql >/dev/null 2>&1 || USE_DOCKER_PSQL=1
	if docker ps -a -q -f "name=^${CONTAINER}$" | grep -q .; then
		if ! docker ps -q -f "name=^${CONTAINER}$" | grep -q .; then
			log "Starting container $CONTAINER"
			docker start "$CONTAINER" >/dev/null
		fi
	else
		log "Starting container $CONTAINER ($IMAGE) on $HOST:$PORT"
		docker run -d --name "$CONTAINER" \
			-e POSTGRES_USER="$DBUSER" -e POSTGRES_PASSWORD="$DBPASS" -e POSTGRES_DB=postgres \
			-p "$HOST:$PORT:5432" "$IMAGE" >/dev/null
	fi
	wait_until_ready
else
	die "no Postgres found. Install Postgres (initdb/pg_ctl) or Docker, or point
DEV_PG_HOST/DEV_PG_PORT/DEV_PG_USER/DEV_PG_PASSWORD at a server where that role
can create databases (or set DEV_PG_ADMIN_URL to a superuser URL for it)."
fi

# --- 2. Database, schema and seed --------------------------------------------

if [ "$(psql_dev postgres -tAc "SELECT 1 FROM pg_database WHERE datname = '$DB'")" != 1 ]; then
	log "Creating database $DB"
	psql_dev postgres -c "CREATE DATABASE \"$DB\" OWNER \"$DBUSER\""
fi

if [ "$(psql_dev "$DB" -tAc "SELECT 1 FROM pg_namespace WHERE nspname = 'clubfindr'")" != 1 ]; then
	log "Loading dev/schema.sql"
	# \restrict/\unrestrict only exist in psql from the August 2025 minor
	# releases onward; drop them so older clients can load the dump too.
	grep -vE '^\\(un)?restrict ' "$DEV_DIR/schema.sql" | psql_dev "$DB" >/dev/null
else
	log "Schema clubfindr already exists; not reloading it"
fi

# Guard, checked against the live connection: the seed wipes every table
CONNECTED_DB=$(psql_dev "$DB" -tAc 'SELECT current_database()')
echo "==> Seed target: database '$CONNECTED_DB' as $DBUSER on $HOST:$PORT"
if [ "$CONNECTED_DB" != "$SEED_DB" ] || [ "$PORT" != "$SEED_PORT" ]; then
	die "refusing to load seed.sql: it only goes into '$SEED_DB' on port $SEED_PORT"
fi
log "Loading dev/seed.sql (replaces all rows in the clubfindr tables)"
psql_dev "$DB" <"$DEV_DIR/seed.sql"

# --- 3. .env -----------------------------------------------------------------

if [ -f "$ENV_FILE" ] && ! head -n 1 "$ENV_FILE" | grep -qF "$ENV_MARKER" && [ $FORCE != 1 ]; then
	log "Leaving the existing .env alone: dev/setup.sh did not write it."
	echo "    Re-run with --force to replace it (a copy is kept as .env.bak)."
else
	[ -f "$ENV_FILE" ] && [ $FORCE = 1 ] && cp "$ENV_FILE" "$ENV_FILE.bak"
	[ -f "$APP_DIR/.env.example" ] || die ".env.example not found in $APP_DIR"

	# Keep the generated secrets across runs so existing cookies stay valid
	old() { [ -f "$ENV_FILE" ] && sed -n "s/^$1=//p" "$ENV_FILE" | head -n 1 || true; }
	random_secret() { od -An -N32 -tx1 /dev/urandom | tr -d ' \n'; }
	CRYPTO_KEY=$(old CRYPTO_KEY)
	[ ${#CRYPTO_KEY} -ge 32 ] || CRYPTO_KEY=$(random_secret)
	JWT=$(old JWT_SECRET)
	[ ${#JWT} -ge 32 ] || JWT=$(random_secret)

	tmp=$(mktemp)
	{
		echo "$ENV_MARKER from .env.example. Local test settings only."
		echo "# External API keys are placeholders; see dev/TESTING.md."
		awk -v host="$HOST" -v port="$PORT" -v db="$DB" -v user="$DBUSER" -v pass="$DBPASS" \
			-v crypto="$CRYPTO_KEY" -v jwt="$JWT" '
			BEGIN { FS = OFS = "=" }
			/^PG_HOST=/     { print $1, host; next }
			/^PG_PORT=/     { print $1, port; next }
			/^PG_DB=/       { print $1, db; next }
			/^PG_USERNAME=/ { print $1, user; next }
			/^PG_PASSWORD=/ { print $1, pass; next }
			/^DATABASE_URL=/     { print $1, "postgres://" user ":" pass "@" host ":" port "/" db; next }
			/^CRYPTO_KEY=/  { print $1, crypto; next }
			/^JWT_SECRET=/       { print $1, jwt; next }
			/^MAIL_TRANSPORT=/   { print $1, "capture"; next }
			{ print }
		' "$APP_DIR/.env.example"
	} >"$tmp"
	mv "$tmp" "$ENV_FILE"
	chmod 600 "$ENV_FILE"
	log "Wrote .env (database $DB on $HOST:$PORT)"
fi

cat <<EOF

Done ($MODE Postgres). Database: postgres://$DBUSER:***@$HOST:$PORT/$DB
Next (see dev/TESTING.md):
  pnpm build && node --env-file=.env build/index.js    # http://localhost:3000
Test logins: listener@clubfindr.test / Listener#2026   (regular user, /login/users)
             promoter@clubfindr.test / Promoter#2026   (promoter, /login/bars)
             bar@clubfindr.test      / BarManager#2026 (bar manager, /login/bars)
             fan@clubfindr.test      / Fan#2026        (regular user without Spotify,
                                                        favourite artists, /login/users)
             newcomer@clubfindr.test / Newcomer#2026   (regular user without Spotify,
                                                        empty taste profile, /login/users)
EOF
